#!/usr/bin/env bash
# Writes docker-compose.snapshot.yaml from the images `goreleaser release --snapshot` just
# built, so `task up:local` runs working-tree code.
#
# It reads dist/artifacts.json rather than `docker images`, because a snapshot loads all
# three images into one local repository — goreleaser.ko.local, with no image name — where
# they are told apart only by a digest tag that changes every build. artifacts.json maps each
# one back to the kos entry that built it.
set -euo pipefail

command -v jq > /dev/null || {
  echo "snapshot-override.sh needs jq" >&2
  exit 1
}

[[ -f dist/artifacts.json ]] || {
  echo "snapshot-override.sh: no dist/artifacts.json; run goreleaser release --snapshot" >&2
  exit 1
}

{
  echo "# Generated by hack/snapshot-override.sh. Do not edit: every snapshot build"
  echo "# produces new digests. \`task up:local\` regenerates it."
  echo "services:"
  # kos build id -> compose service name. horoctl's image runs as the bootstrap service;
  # every other id names its own service.
  for pair in horoctl-migrate:horoctl-migrate ingress:ingress egress:egress horoctl:bootstrap; do
    id="${pair%%:*}"
    service="${pair#*:}"
    ref="$(jq -r --arg id "$id" \
      '.[] | select(.type == "Docker Manifest" and .extra.ID == $id) | .name' \
      dist/artifacts.json | sed 's|^index.docker.io/library/||')"
    [[ -n $ref ]] || {
      echo "snapshot-override.sh: no image for $id in dist/artifacts.json" >&2
      exit 1
    }
    printf '  %s:\n    image: %s\n' "$service" "$ref"
  done
} > docker-compose.snapshot.yaml
