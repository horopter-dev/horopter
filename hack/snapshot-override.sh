#!/usr/bin/env bash
# Not `docker images`: a snapshot's images share one repository, told apart only by digest.
set -euo pipefail

command -v jq > /dev/null || {
  echo "snapshot-override.sh needs jq" >&2
  exit 1
}

[[ -f dist/artifacts.json ]] || {
  echo "snapshot-override.sh: no dist/artifacts.json; run goreleaser release --snapshot" >&2
  exit 1
}

{
  echo "# Generated by hack/snapshot-override.sh. Do not edit: every snapshot build"
  echo "# produces new digests. \`task up:local\` regenerates it."
  echo "services:"
  # kos build id -> compose service name; horoctl's image runs as the bootstrap service.
  for pair in horopter-migrate:horopter-migrate ingress:ingress egress:egress horoctl:bootstrap; do
    id="${pair%%:*}"
    service="${pair#*:}"
    ref="$(jq -r --arg id "$id" \
      '.[] | select(.type == "Docker Manifest" and .extra.ID == $id) | .name' \
      dist/artifacts.json | sed 's|^index.docker.io/library/||')"
    [[ -n $ref ]] || {
      echo "snapshot-override.sh: no image for $id in dist/artifacts.json" >&2
      exit 1
    }
    printf '  %s:\n    image: %s\n' "$service" "$ref"
  done
} > docker-compose.snapshot.yaml
